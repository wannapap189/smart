export function moldedGallery() {
  return collections.map(({id, title, intro, items}) => {
    const cards = items.map(([file, name, description, alt, source, link]) => {
      const image = directory + file + '.webp';
      const wide = file === 'fanta-citrus-pouch';
      return `<article class="molded-card">
        <a class="molded-photo" href="${image}" aria-label="ดูภาพใหญ่ · ${name}">
          <img src="${image}" alt="${alt}" width="${wide ? 1280 : 1200}" height="${wide ? 640 : 900}" loading="lazy" decoding="async">
        </a>
        <div class="molded-copy"><h3>${name}</h3><p>${description}</p>
        ${link ? `<a class="text-link" href="${link}" target="_blank" rel="noopener">ดูวัสดุจาก ${source} ↗</a>` : ''}</div>
      </article>`;
    }).join('');
    return `<section class="section container molded-section" id="${id}"><h2>${title}</h2><p>${intro}</p>
      <div class="molded-grid">${cards}</div></section>`;
  }).join('');
}
